"""
Canonical source of truth for stock themes (產業鏈分類).

Human-edited by STOCK NAME (股名), not stock code — names are unique among
active common stocks, so this avoids the wrong-code bugs that plagued the old
code-based seed. The loader (db.seed_themes) resolves names -> stock_id against
tw.stocks and refuses to write if any name fails to resolve.

Edit this file, then run:
    python -m db.seed_themes --check   # validate only, no DB write
    python -m db.seed_themes           # sync DB to match this file exactly

DB is a full mirror of this file: themes/mappings not listed here are removed.

Format:
    THEMES  = [(name, category, subcategory, description), ...]
    MAPPINGS = {theme_path: ["股名", "股名", ...], ...}
theme_path is "category > subcategory > name"; the full path is the key
because a theme name is only unique within its branch. category is the
industry (半導體 / 電子基板), subcategory the segment of that chain.

Membership rule:
  Broad themes (many members, used to watch a sector rotate) take a company
  when the business reaches about a fifth of revenue. The bar sits at 20%
  rather than higher because Taiwanese PCB revenue shares cluster at the two
  ends — a firm is either a pure play above 90% or lands under 20%, and the
  20~30% band is empty — so a stricter bar buys no extra purity, while 20%
  still keeps out 華盈 (19%, a wire-harness maker).
  Niche themes (few members, used to ask "who works in this corner") judge by
  absolute scale instead. A product line worth 18% of a large firm can outsize
  a small pure-play entirely, so excluding it by ratio is the bigger
  distortion. 特殊材質基板 holds 同欣電 (ceramic substrate ~18% of revenue,
  but larger in absolute terms than 九豪 as a whole) on this basis.

Evidence:
  Most memberships are read straight off the annual report's 營業比重 table
  and need nothing recorded here. The rest are listed in MANUAL_EVIDENCE,
  because the table is written at whatever granularity the company chose:
  searching every 2025 filing for 光阻 or 靶材 returns zero rows even though
  新應材 and 光洋科 are pure plays. Those fall back to the report's prose, an
  investor-conference deck, or the company's own product pages, and each one
  says which. 'pending' means the membership was carried over and still owes
  an evidence line.
"""

